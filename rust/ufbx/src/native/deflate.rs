// ufbx.c:2204-2248 `ufbxi_bit_copy_bytes`
#[inline(never)]
pub(crate) unsafe fn bit_copy_bytes(dst: *mut c_void, s: *mut BitStream, len: usize) -> i32 {
    // `s.buffer` may point into `s.local_buffer` (see `bit_stream_init`), i.e.
    // the `BitStream` holds a raw pointer aliasing one of its own fields, so `s`
    // stays raw and is derefed as `(*s).field` to avoid a whole-struct retag
    // invalidating that interior pointer.

    ufbx_assert!((*s).left % 8 == 0);
    let mut len = len;
    let mut ptr = dst as *mut u8;

    // Copy the buffered bits first
    while len > 0 && (*s).left > 0 {
        // C: `*ptr++ = (char)(uint8_t)s->bits;`
        *ptr = (*s).bits as u8;
        ptr = ptr.add(1);
        len -= 1;
        (*s).bits >>= 8;
        (*s).left -= 8;
    }

    // Copied fully from buffer
    if len == 0 {
        return 1;
    }

    // We need to clear the top bits as there may be data
    // read ahead past `s->left` in some cases
    (*s).bits = 0;

    // Copy the current chunk
    let chunk_left = to_size((*s).chunk_real_end.offset_from((*s).chunk_ptr));
    if chunk_left >= len {
        // C: memcpy(ptr, s->chunk_ptr, len)
        core::ptr::copy_nonoverlapping((*s).chunk_ptr, ptr, len);
        (*s).chunk_ptr = (*s).chunk_ptr.add(len);
        return 1;
    } else {
        core::ptr::copy_nonoverlapping((*s).chunk_ptr, ptr, chunk_left);
        (*s).chunk_ptr = (*s).chunk_ptr.add(chunk_left);
        ptr = ptr.add(chunk_left);
        len -= chunk_left;
    }

    // Read extra bytes from user
    if len > (*s).input_left {
        return 0;
    }
    let mut num_read = 0usize;
    if (*s).read_fn.is_some() {
        num_read = ((*s).read_fn.unwrap())((*s).read_user, ptr as *mut c_void, len);
        // C-parity: no clamp on `num_read` here (unlike ufbxi_bit_chunk_refill,
        // ufbx.c:2068); a misbehaving read_fn wraps `input_left` in size_t and
        // the function returns 0 below.
        (*s).input_left = (*s).input_left.wrapping_sub(num_read);
    }
    (num_read == len) as i32
}

// C comment (ufbx.c:2250-2252):
// 0: Success
// -1: Overfull
// -2: Underfull
// ufbx.c:2253-2453 `ufbxi_huff_build_imp`
#[inline(never)]
pub(crate) unsafe fn huff_build_imp(
    tree: *mut HuffTree,
    sym_bits: *const u8,
    sym_count: u32,
    sym_extra: *const u32,
    sym_extra_offset: u32,
    fast_bits: u32,
    bits_counts: &mut [u32; HUFF_MAX_BITS],
) -> isize {
    // Sole raw pointer to `*tree` in this function (rule 4): local exclusive
    // borrow for the whole body in place of repeated `(*tree).field` derefs.
    let tree = &mut *tree;

    let fast_mask = (1u32 << fast_bits) - 1;

    ufbx_assert!(sym_count as usize <= HUFF_MAX_VALUE);
    tree.num_symbols = sym_count;

    let nonzero_sym_count = sym_count - bits_counts[0];

    let mut total_syms = [0u32; HUFF_MAX_BITS]; // ufbxi_uninit
    let mut first_code = [0u32; HUFF_MAX_BITS]; // ufbxi_uninit

    tree.code_to_sorted[0] = i16::MAX;
    tree.past_max_code[0] = 0;
    total_syms[0] = 0;

    // Clear to uninitialized symbols
    #[cfg(feature = "regression")]
    {
        for i in 0..HUFF_FAST_SIZE {
            tree.fast_sym[i] = HUFF_UNINITIALIZED_SYM;
        }
        for i in 0..HUFF_MAX_VALUE {
            tree.sorted_to_sym[i] = HUFF_UNINITIALIZED_SYM;
        }
        for i in 0..HUFF_MAX_LONG_SYMS {
            tree.long_sym[i] = HUFF_UNINITIALIZED_SYM;
        }
    }

    let mut last_valid_prefix = 0u32;

    // Resolve the maximum code per bit length and ensure that the tree is not
    // overfull or underfull.
    {
        let mut num_codes_left: i32 = 1;
        let mut code = 0u32;
        let mut prev_count = 0u32;
        let mut long_offset = 0u32;
        for bits in 1..HUFF_MAX_BITS as u32 {
            let count = bits_counts[bits as usize];
            code = (code + prev_count) << 1;
            first_code[bits as usize] = code;
            tree.past_max_code[bits as usize] = (code + count) as u16;

            let prev_syms = total_syms[(bits - 1) as usize];
            total_syms[bits as usize] = prev_syms + count;

            // Each bit level doubles the amount of codes and potentially removes some
            num_codes_left = (num_codes_left << 1) - count as i32;
            if num_codes_left < 0 {
                return -1;
            }

            if count > 0 && bits > fast_bits && bits - fast_bits <= HUFF_MAX_LONG_BITS {
                let shift = bits - fast_bits;
                let last_inclusive = if num_codes_left == 0 {
                    (1u32 << shift) - 1u32
                } else {
                    0u32
                };
                let first_prefix = code >> shift;
                let last_prefix = (code + count + last_inclusive) >> shift;
                let mask = (1u32 << shift) - 1u32;
                let half_step = 1u32 << (shift - 1u32);
                for prefix in first_prefix..last_prefix {
                    let rev_prefix = bit_reverse(prefix, fast_bits);
                    tree.fast_sym[rev_prefix as usize] = (mask | (long_offset << 8)) as HuffSym;
                    long_offset += half_step;
                }

                last_valid_prefix = last_prefix;
            }

            if count > 0 {
                tree.code_to_sorted[bits as usize] = (prev_syms as i32 - code as i32) as i16;
            } else {
                tree.code_to_sorted[bits as usize] = i16::MAX;
            }
            prev_count = count;
        }

        // All codes should be used if there's more than one symbol, if there's only one symbol there should be
        // only a single 1-bit code.
        if nonzero_sym_count > 1 && num_codes_left != 0 {
            return -2;
        } else if nonzero_sym_count == 1 && total_syms[1] != 1 {
            return -2;
        }

        // We should always have enough space for long symbols as we support up to 5 (UFBXI_HUFF_MAX_LONG_BITS)
        // bits and the largest tree has 286 symbols. For each bit we may waste at most 2^bits slots (conservative)
        // and in the end we may waste 2^5 slots giving us `286+2+4+8+16+32+32 = 380` (UFBXI_HUFF_MAX_LONG_SYMS)
        ufbx_assert!(long_offset as usize <= HUFF_MAX_LONG_SYMS);
    }

    tree.end_of_block_bits = 0;

    let mut num_extra = 0u32;
    tree.extra_shift_base[0] = 0;
    tree.extra_mask[0] = 0;

    // Fill `fast_sym[]` with error symbols if necessary, we don't need to do this if we have two or more symbols
    // as the tree is guaranteed to be full, which means we will populate the whole `fast_sym[]`
    if nonzero_sym_count <= 1 {
        for i in 0..=fast_mask {
            tree.fast_sym[i as usize] = HUFF_ERROR_SYM;
        }
    }

    // Generate per-length sorted-to-symbol and fast lookup tables
    let mut bits_index = [0u32; HUFF_MAX_BITS];
    for i in 0..sym_count {
        let bits = *sym_bits.add(i as usize) as u32;
        if bits == 0 {
            continue;
        }

        let mut sym = i << 8 | bits;
        if i >= sym_extra_offset {
            let extra = *sym_extra.add((i - sym_extra_offset) as usize);
            sym += extra;

            // Store length/distance codes with extra values in a table.
            // TODO: This is unnecessary for small values
            if (extra & 0xffff001f) != 0 && (extra & 0x20) == 0 {
                // C: `uint32_t ix = ++num_extra;`
                num_extra += 1;
                let ix = num_extra;
                tree.extra_shift_base[ix as usize] = (extra & 0xffff0000) | bits;
                tree.extra_mask[ix as usize] = ((1u32 << (extra & 0x1f)) - 1) as u16;
                sym = (sym & 0xff) | ix << 8;
            }
        }

        // C: `uint32_t index = bits_index[bits]++;`
        let index = bits_index[bits as usize];
        bits_index[bits as usize] += 1;
        let sorted = total_syms[(bits - 1) as usize] + index;
        tree.sorted_to_sym[sorted as usize] = sym as HuffSym;

        // Reverse the code and fill all fast lookups with the reversed prefix
        let code = first_code[bits as usize] + index;
        let rev_code = bit_reverse(code, bits);

        if bits <= fast_bits {
            let mut fast_sym = sym;
            // The `end` and `fast` flags are mutually exclusive
            if (fast_sym & HUFF_SYM_END) == 0 {
                fast_sym |= HUFF_SYM_FAST;
            }
            let hi_max = 1u32 << (fast_bits - bits);
            for hi in 0..hi_max {
                ufbxi_regression_assert!(
                    nonzero_sym_count <= 1
                        || tree.fast_sym[(rev_code | hi << bits) as usize]
                            == HUFF_UNINITIALIZED_SYM
                );
                tree.fast_sym[(rev_code | hi << bits) as usize] = fast_sym as HuffSym;
            }
        } else if bits <= fast_bits + HUFF_MAX_LONG_BITS
            && (code >> (bits - fast_bits)) < last_valid_prefix
        {
            let fast_sym = tree.fast_sym[(rev_code & fast_mask) as usize] as u32;
            // C: `fast_sym != UFBXI_HUFF_UNINITIALIZED_SYM` — uint32 vs uint16
            // constant, compared after integer promotion (in u32).
            ufbxi_regression_assert!(fast_sym != HUFF_UNINITIALIZED_SYM as u32);
            let mut long_bits = 0u32;

            let mut long_mask = fast_sym;
            while long_bits < HUFF_MAX_LONG_BITS && (long_mask & 1) != 0 {
                long_mask >>= 1;
                long_bits += 1;
            }
            ufbxi_dev_assert!(long_bits >= 1);

            let long_base = fast_sym >> 7u32; // aka (fast_sym >> 8) * 2
            let lo_bits = bits - fast_bits;
            let hi_max = 1u32 << (long_bits - lo_bits);
            let rev_suffix = rev_code >> fast_bits;
            for hi in 0..hi_max {
                ufbxi_regression_assert!(
                    tree.long_sym[(long_base + (rev_suffix | hi << lo_bits)) as usize]
                        == HUFF_UNINITIALIZED_SYM
                );
                tree.long_sym[(long_base + (rev_suffix | hi << lo_bits)) as usize] = sym as HuffSym;
            }
        } else {
            let fast_sym = (code >> (bits - fast_bits)) << 8;
            ufbxi_regression_assert!(
                tree.fast_sym[(rev_code & fast_mask) as usize] == HUFF_UNINITIALIZED_SYM
                    || tree.fast_sym[(rev_code & fast_mask) as usize] == fast_sym as HuffSym
            );
            tree.fast_sym[(rev_code & fast_mask) as usize] = fast_sym as HuffSym;
        }

        // Make sure the end-of-block symbol goes through the slow path
        // Also store the end-of-block code so we can interrupt decoding
        if i == 256 {
            tree.end_of_block_bits = rev_code;
        }
    }

    // Make sure all `fast_sym[]` are filled with an initialized value.
    #[cfg(feature = "regression")]
    {
        for i in 0..HUFF_FAST_SIZE {
            if i <= fast_mask as usize {
                ufbx_assert!(tree.fast_sym[i] != HUFF_UNINITIALIZED_SYM);
            } else {
                ufbx_assert!(tree.fast_sym[i] == HUFF_UNINITIALIZED_SYM);
            }
        }
        for i in 0..nonzero_sym_count as usize {
            ufbx_assert!(tree.sorted_to_sym[i] != HUFF_UNINITIALIZED_SYM);
        }
    }

    0
}

// C comment (ufbx.c:2455-2457):
// 0: Success
// -1: Overfull
// -2: Underfull
// ufbx.c:2458-2472 `ufbxi_huff_build`
#[inline(never)]
pub(crate) unsafe fn huff_build(
    tree: *mut HuffTree,
    sym_bits: *const u8,
    sym_count: u32,
    sym_extra: *const u32,
    sym_extra_offset: u32,
    fast_bits: u32,
) -> isize {
    // Count the number of codes per bit length
    // `bits_counts[0]` contains the number of non-used symbols
    // C: `uint32_t bits_counts[UFBXI_HUFF_MAX_BITS]; // ufbxi_uninit` + memset
    let mut bits_counts = [0u32; HUFF_MAX_BITS];
    for i in 0..sym_count {
        let bits = *sym_bits.add(i as usize) as u32;
        ufbx_assert!((bits as usize) < HUFF_MAX_BITS);
        bits_counts[bits as usize] += 1;
    }

    huff_build_imp(
        tree,
        sym_bits,
        sym_count,
        sym_extra,
        sym_extra_offset,
        fast_bits,
        &mut bits_counts,
    )
}

// ufbx.c:2474-2508 `ufbxi_huff_decode_bits`
// C: `static ufbxi_forceinline ufbxi_huff_sym`.
#[inline(always)]
pub(crate) unsafe fn huff_decode_bits(
    tree: *const HuffTree,
    bits: u64,
    fast_bits: u32,
    fast_mask: u32,
) -> HuffSym {
    // Sole raw pointer to `*tree` in this function (rule 4): local shared
    // borrow for the whole body in place of repeated `(*tree).field` derefs.
    let tree = &*tree;

    let mut sym: HuffSym = tree.fast_sym[(bits & fast_mask as u64) as usize];
    ufbxi_regression_assert!(sym != HUFF_UNINITIALIZED_SYM);

    if (sym as u32 & (HUFF_SYM_FAST | HUFF_SYM_END)) != 0 {
        return sym;
    }

    let mut tail = (bits >> fast_bits) as u32;
    let long_mask = huff_sym_long_mask(sym);
    if long_mask != 0 {
        sym = tree.long_sym[(huff_sym_long_offset(sym) + (tail & long_mask)) as usize];
        ufbxi_regression_assert!(sym != HUFF_UNINITIALIZED_SYM);
        return sym;
    }

    ufbxi_dev_assert!(fast_bits <= 8);

    let mut code = huff_sym_value(sym);
    let mut num_bits = fast_bits;
    loop {
        code = code << 1 | (tail & 1);
        tail >>= 1;
        num_bits += 1;

        ufbxi_regression_assert!((num_bits as usize) < HUFF_MAX_BITS);
        if code < tree.past_max_code[num_bits as usize] as u32 {
            // C: `sorted_to_sym[(int32_t)code + (int32_t)tree->code_to_sorted[num_bits]]`
            sym = tree.sorted_to_sym
                [(code as i32 + tree.code_to_sorted[num_bits as usize] as i32) as usize];
            ufbxi_regression_assert!(sym != HUFF_UNINITIALIZED_SYM);
            return sym;
        }
    }
}

// ufbx.c:2510-2538 `ufbxi_init_static_huff`
// NOTE: `input` may be NULL (called with NULL from `ufbxi_inflate_init_retain`).
#[inline(never)]
pub(crate) unsafe fn init_static_huff(trees: *mut Trees, input: *const InflateInput) {
    // `trees` is the sole raw pointer to that `Trees` in this function (rule
    // 4): local exclusive borrow in place of repeated `(*trees).field`
    // derefs. `input` is left as a raw pointer — it may legitimately be
    // NULL here (see the fn doc comment), so an unconditional `&*input`
    // reference is not obviously sound.
    let trees = &mut *trees;
    let mut err: isize = 0;

    // Override `fast_bits` if necessary, this must always be valid as it's checked in the beginning of `ufbx_inflate()`.
    if !input.is_null() && (*input).internal_fast_bits != 0 {
        trees.fast_bits = (*input).internal_fast_bits as u32;
        ufbx_assert!(!(trees.fast_bits < 1 || trees.fast_bits == 9 || trees.fast_bits > 10));
    } else {
        trees.fast_bits = HUFF_FAST_BITS;
    }

    // 0-143: 8 bits, 144-255: 9 bits, 256-279: 7 bits, 280-287: 8 bits
    let mut lit_length_bits = [0u8; 288]; // ufbxi_uninit
    lit_length_bits[0..144].fill(8);
    lit_length_bits[144..256].fill(9);
    lit_length_bits[256..280].fill(7);
    lit_length_bits[280..288].fill(8);
    err |= huff_build(
        trees.lit_length_mut(),
        lit_length_bits.as_ptr(),
        size_of::<[u8; 288]>() as u32,
        DEFLATE_LENGTH_LUT.as_ptr(),
        256,
        trees.fast_bits,
    );

    // "Distance codes 0-31 are represented by (fixed-length) 5-bit codes"
    let mut dist_bits = [0u8; 32]; // ufbxi_uninit
    dist_bits[0..32].fill(5);
    err |= huff_build(
        trees.dist_mut(),
        dist_bits.as_ptr(),
        size_of::<[u8; 32]>() as u32,
        DEFLATE_DIST_LUT.as_ptr(),
        0,
        trees.fast_bits,
    );

    // Building the static trees cannot fail as we use pre-defined code lengths.
    ufbxi_ignore!(err);
    ufbx_assert!(err == 0);
}

// ufbx.c:2540-2601 `ufbxi_decode_dynamic_huff_bits`
#[inline(never)]
pub(crate) unsafe fn decode_dynamic_huff_bits(
    dc: &DeflateContext,
    huff_code_length: *const HuffTree,
    code_lengths: *mut u8,
    num_symbols: u32,
) -> isize {
    // `(*dc.get()).stream` holds a self-referential `buffer`→`local_buffer` pointer (see
    // `bit_stream_init`), so `dc` stays raw and is derefed as `(*dc.get()).field` to
    // avoid a whole-struct retag invalidating that interior pointer.

    let mut bits = (*dc.get()).stream.bits;
    let mut left = (*dc.get()).stream.left;
    let mut data = (*dc.get()).stream.chunk_ptr;

    let mut symbol_index = 0u32;
    let mut prev = 0u8;
    while symbol_index < num_symbols {
        bit_refill(&mut bits, &mut left, &mut data, dc.stream_mut_ptr());
        if (*dc.get()).stream.cancelled {
            return -28;
        }

        let sym: HuffSym = huff_decode_bits(
            huff_code_length,
            bits,
            HUFF_CODELEN_FAST_BITS,
            HUFF_CODELEN_FAST_MASK,
        );
        ufbxi_regression_assert!(sym != HUFF_UNINITIALIZED_SYM);
        if sym == HUFF_ERROR_SYM {
            return -21;
        }

        let inst = huff_sym_value(sym);
        let sym_len = huff_sym_total_bits(sym);

        bits >>= sym_len;
        left -= sym_len as usize;

        if inst <= 15 {
            // "0 - 15: Represent code lengths of 0 - 15"
            prev = inst as u8;
            // C: `code_lengths[symbol_index++] = (uint8_t)inst;`
            *code_lengths.add(symbol_index as usize) = inst as u8;
            symbol_index += 1;
        } else if inst == 16 {
            // "16: Copy the previous code length 3 - 6 times. The next 2 bits indicate repeat length."
            let num = 3 + (bits as u32 & 0x3);
            bits >>= 2;
            left -= 2;
            if symbol_index + num > num_symbols {
                return -18;
            }
            // C: memset(code_lengths + symbol_index, prev, num)
            core::ptr::write_bytes(code_lengths.add(symbol_index as usize), prev, num as usize);
            symbol_index += num;
        } else if inst == 17 {
            // "17: Repeat a code length of 0 for 3 - 10 times. (3 bits of length)"
            let num = 3 + (bits as u32 & 0x7);
            bits >>= 3;
            left -= 3;
            if symbol_index + num > num_symbols {
                return -19;
            }
            core::ptr::write_bytes(code_lengths.add(symbol_index as usize), 0, num as usize);
            symbol_index += num;
            prev = 0;
        } else if inst == 18 {
            // "18: Repeat a code length of 0 for 11 - 138 times (7 bits of length)"
            let num = 11 + (bits as u32 & 0x7f);
            bits >>= 7;
            left -= 7;
            if symbol_index + num > num_symbols {
                return -20;
            }
            core::ptr::write_bytes(code_lengths.add(symbol_index as usize), 0, num as usize);
            symbol_index += num;
            prev = 0;
        } else {
            return -6;
        }
    }

    (*dc.get()).stream.bits = bits;
    (*dc.get()).stream.left = left;
    (*dc.get()).stream.chunk_ptr = data;

    0
}

// ufbx.c:2603-2662 `ufbxi_init_dynamic_huff`
#[inline(never)]
pub(crate) unsafe fn init_dynamic_huff(dc: &DeflateContext, trees: *mut Trees) -> isize {
    // `(*dc.get()).stream` holds a self-referential `buffer`→`local_buffer` pointer (see
    // `bit_stream_init`), so `dc` stays raw and is derefed as `(*dc.get()).field` to
    // avoid a whole-struct retag invalidating that interior pointer. `trees` is
    // not self-referential, so a local exclusive borrow is kept for it.
    let trees = &mut *trees;

    let mut bits = (*dc.get()).stream.bits;
    let mut left = (*dc.get()).stream.left;
    let mut data = (*dc.get()).stream.chunk_ptr;
    bit_refill(&mut bits, &mut left, &mut data, dc.stream_mut_ptr());
    if (*dc.get()).stream.cancelled {
        return -28;
    }

    trees.fast_bits = dc.fast_bits();

    // The header contains the number of Huffman codes in each of the three trees.
    let num_lit_lengths = 257 + (bits & 0x1f) as u32;
    let num_dists = 1 + (bits >> 5 & 0x1f) as u32;
    let num_code_lengths = 4 + (bits >> 10 & 0xf) as u32;
    bits >>= 14;
    left -= 14;

    // C: `uint8_t code_lengths[UFBXI_HUFF_MAX_COMBINED_SYMS]; // ufbxi_uninit`
    // followed by `memset(code_lengths, 0, UFBXI_HUFF_CODELEN_SYMS)`; zero-init
    // covers the memset, C never reads past what is subsequently written.
    let mut code_lengths = [0u8; HUFF_MAX_COMBINED_SYMS]; // ufbxi_uninit

    // Code lengths for the "code length" Huffman tree are represented literally
    // 3 bits in order of: 16,17,18,0,8,7,9,6,10,5,11,4,12,3,13,2,14,1,15 up to
    // `num_code_lengths`, rest of the code lengths are 0 (unused)

    for len_i in 0..num_code_lengths as usize {
        if len_i == 14 {
            bit_refill(&mut bits, &mut left, &mut data, dc.stream_mut_ptr());
            if (*dc.get()).stream.cancelled {
                return -28;
            }
        }
        code_lengths[DEFLATE_CODE_LENGTH_PERMUTATION[len_i] as usize] = (bits as u32 & 0x7) as u8;
        bits >>= 3;
        left -= 3;
    }

    (*dc.get()).stream.bits = bits;
    (*dc.get()).stream.left = left;
    (*dc.get()).stream.chunk_ptr = data;

    // C: `ufbxi_huff_tree huff_code_length; // ufbxi_uninit` — zero-init,
    // `ufbxi_huff_build` writes everything that is later read.
    let mut huff_code_length: HuffTree = core::mem::zeroed(); // ufbxi_uninit
    let mut err: isize; // ufbxi_uninit

    // Build the temporary "code length" Huffman tree used to encode the actual
    // trees used to compress the data. Use that to build the literal/length and
    // distance trees.
    err = huff_build(
        &mut huff_code_length,
        code_lengths.as_ptr(),
        HUFF_CODELEN_SYMS as u32,
        core::ptr::null(),
        i32::MAX as u32,
        HUFF_CODELEN_FAST_BITS,
    );
    if err != 0 {
        return -14 + 1 + err;
    }

    err = decode_dynamic_huff_bits(
        dc,
        &huff_code_length,
        code_lengths.as_mut_ptr(),
        num_lit_lengths + num_dists,
    );
    if err != 0 {
        return err;
    }

    err = huff_build(
        trees.lit_length_mut(),
        code_lengths.as_ptr(),
        num_lit_lengths,
        DEFLATE_LENGTH_LUT.as_ptr(),
        256,
        dc.fast_bits(),
    );
    if err != 0 {
        return if err == -7 { -28 } else { -16 + 1 + err };
    }

    err = huff_build(
        trees.dist_mut(),
        code_lengths.as_ptr().add(num_lit_lengths as usize),
        num_dists,
        DEFLATE_DIST_LUT.as_ptr(),
        0,
        dc.fast_bits(),
    );
    if err != 0 {
        return if err == -7 { -28 } else { -22 + 1 + err };
    }

    0
}

// ufbx.c:2664-2803 `ufbxi_adler32`
// C-parity: C has three inner-loop variants — SSE (`UFBXI_HAS_SSE`), a scalar
// 64-bit SWAR loop (`UFBX_LITTLE_ENDIAN`), and the plain byte loop. All three
// produce bit-identical sums (the SIMD/SWAR forms are pure strength
// reductions of the same modular arithmetic); the Rust port carries the SWAR
// branch (ufbx.c:2746-2790) on little-endian targets and the plain loop
// otherwise — the SSE branch is intentionally not ported.
#[inline(never)]
pub(crate) unsafe fn adler32(data: *const c_void, size: usize) -> u32 {
    let mut a: FastUint = 1;
    let mut b: FastUint = 0;
    let mut p = data as *const u8;

    // Adler-32 consists of two running sums modulo 65521. As an optimization
    // we can accumulate N sums before applying the modulo, where N depends on
    // the size of the type holding the sum.
    let num_before_wrap: FastUint = if size_of::<FastUint>() == 8 {
        380368439
    } else {
        5552
    };

    let mut size_left = size as FastUint;
    while size_left > 0 {
        let num = if size_left <= num_before_wrap {
            size_left
        } else {
            num_before_wrap
        };
        size_left -= num;
        let end = p.add(num as usize);

        // Align to 16 bytes
        while p != end && !is_aligned(p, 16) {
            a += *p as FastUint;
            b += a;
            p = p.add(1);
        }

        // ufbx.c:2746-2790 `#elif UFBX_LITTLE_ENDIAN` scalar SWAR branch
        #[cfg(target_endian = "little")]
        {
            loop {
                let chunk_size = min_sz(to_size(end.offset_from(p)), 256 * 8 / 4) & !0xfusize;
                if chunk_size == 0 {
                    break;
                }
                let chunk_end = p.add(chunk_size);

                let mut s1_lo: u64 = 0;
                let mut s1_hi: u64 = 0;
                let mut tmp: u64;
                let mut s2: u64 = 0;
                let mask8: u64 = 0x00ff00ff00ff00ff;
                let mask16: u64 = 0x0000ffff0000ffff;

                while p != chunk_end {
                    // C: `*(const uint64_t*)p` — `p` is 16-aligned here;
                    // little-endian native load == `read_u64`.
                    let d0 = read_u64(p);
                    let d1 = read_u64(p.add(8));

                    tmp = s1_lo + s1_hi;
                    s1_lo += d0 & mask8;
                    s1_hi += (d0 >> 8) & mask8;

                    tmp += s1_lo + s1_hi;
                    s1_lo += d1 & mask8;
                    s1_hi += (d1 >> 8) & mask8;

                    s2 += (tmp & mask16) + ((tmp >> 16) & mask16);
                    p = p.add(16);
                }

                let mut s1 = s1_lo + s1_hi;
                s1 = (s1 & mask16) + ((s1 >> 16u32) & mask16);
                let s1_sum = (s1 + (s1 >> 32u32)) as FastUint;

                let mut s2_sum = ((s2 + (s2 >> 32u32)) as FastUint) * 8;
                s2_sum += ((s1_lo >> 0) as FastUint & 0xffff) * 8;
                s2_sum += ((s1_hi >> 0) as FastUint & 0xffff) * 7;
                s2_sum += ((s1_lo >> 16) as FastUint & 0xffff) * 6;
                s2_sum += ((s1_hi >> 16) as FastUint & 0xffff) * 5;
                s2_sum += ((s1_lo >> 32) as FastUint & 0xffff) * 4;
                s2_sum += ((s1_hi >> 32) as FastUint & 0xffff) * 3;
                s2_sum += ((s1_lo >> 48) as FastUint & 0xffff) * 2;
                s2_sum += ((s1_hi >> 48) as FastUint & 0xffff) * 1;

                b += chunk_size as FastUint * a;
                a += s1_sum & 0xffffffff;
                b += s2_sum & 0xffffffff;
            }
        }

        while p != end {
            a += *p as FastUint;
            b += a;
            p = p.add(1);
        }

        a %= 65521;
        b %= 65521;
    }

    ((b << 16) | (a & 0xffff)) as u32
}

// ufbx.c:2805-2904 `ufbxi_inflate_block_slow`
#[inline(never)]
pub(crate) unsafe fn inflate_block_slow(
    dc: &DeflateContext,
    trees: *mut Trees,
    max_symbols: usize,
) -> i32 {
    // `(*dc.get()).stream` holds a self-referential `buffer`→`local_buffer` pointer (see
    // `bit_stream_init`), so `dc` stays raw and is derefed as `(*dc.get()).field` to
    // avoid a whole-struct retag invalidating that interior pointer. `trees` is
    // not self-referential and only ever read here, so a shared borrow suffices.
    let trees = &*trees;

    let mut max_symbols = max_symbols;
    let mut out_ptr = dc.out_ptr();
    let out_begin = dc.out_begin();
    let out_end = dc.out_end();

    let fast_bits = trees.fast_bits;
    let fast_mask = (1u32 << fast_bits) - 1;

    let mut bits = (*dc.get()).stream.bits;
    let mut left = (*dc.get()).stream.left;
    let mut data = (*dc.get()).stream.chunk_ptr;

    loop {
        // C: `if (max_symbols-- == 0) break;` (size_t; wraps past zero)
        let prev_max_symbols = max_symbols;
        max_symbols = max_symbols.wrapping_sub(1);
        if prev_max_symbols == 0 {
            break;
        }

        bit_refill(&mut bits, &mut left, &mut data, dc.stream_mut_ptr());
        let sym_bits = bits;

        let sym0: HuffSym = huff_decode_bits(trees.lit_length(), bits, fast_bits, fast_mask);
        ufbxi_regression_assert!(sym0 != HUFF_UNINITIALIZED_SYM);

        let sym0_bits = huff_sym_total_bits(sym0);

        bits >>= sym0_bits;
        // C-parity: `left` is size_t in C and may transiently wrap below zero
        // on adversarial input; it is masked back by `left |= 56` on refill.
        left = left.wrapping_sub(sym0_bits as usize);
        if (sym0 as u32 & HUFF_SYM_END) != 0 {
            if huff_sym_value(sym0) != 0 {
                return -13;
            }

            dc.set_out_ptr(out_ptr);
            (*dc.get()).stream.bits = bits;
            (*dc.get()).stream.left = left;
            (*dc.get()).stream.chunk_ptr = data;
            return 0;
        } else if (sym0 as u32 & HUFF_SYM_MATCH) == 0 {
            if out_ptr == out_end {
                return -10;
            }
            // C: `*out_ptr++ = (char)ufbxi_huff_sym_value(sym0);`
            *out_ptr = huff_sym_value(sym0) as u8;
            out_ptr = out_ptr.add(1);
            continue;
        }

        let sym0_value = huff_sym_value(sym0);
        let len_shift_base = trees.lit_length().extra_shift_base[sym0_value as usize];
        let len_mask = trees.lit_length().extra_mask[sym0_value as usize];
        let length = (len_shift_base >> 16)
            + (wrap_shr64(sym_bits, len_shift_base) & len_mask as u64) as u32;

        let sym1: HuffSym = huff_decode_bits(trees.dist(), bits, fast_bits, fast_mask);
        ufbxi_regression_assert!(sym1 != HUFF_UNINITIALIZED_SYM);
        if (sym1 as u32 & HUFF_SYM_END) != 0 {
            return -11;
        }

        let sym1_bits = huff_sym_total_bits(sym1);

        bits >>= sym1_bits;
        left = left.wrapping_sub(sym1_bits as usize);

        let sym1_value = huff_sym_value(sym1);
        let dist_shift_base = trees.dist().extra_shift_base[sym1_value as usize];
        let dist_mask = trees.dist().extra_mask[sym1_value as usize];
        let distance = (dist_shift_base >> 16)
            + (wrap_shr64(sym_bits, dist_shift_base + sym0 as u32) & dist_mask as u64) as u32;

        // Bounds checking
        let out_space = to_size(out_end.offset_from(out_ptr));
        if distance as isize > out_ptr.offset_from(out_begin) || length as usize > out_space {
            return -12;
        }

        // Copy the match
        let mut src: *const u8 = out_ptr.sub(distance as usize);
        let mut dst = out_ptr;
        let end = dst.add(length as usize);
        out_ptr = out_ptr.add(length as usize);

        let mut length = length;
        if out_space >= length as usize + 16 {
            let min_dist = if length < 16 { length } else { 16 };
            if distance >= min_dist {
                copy_16_bytes(dst, src);
                while length > 16 {
                    src = src.add(16);
                    dst = dst.add(16);
                    length -= 16;
                    copy_16_bytes(dst, src);
                }
            } else {
                while dst != end {
                    // C: `*dst++ = *src++;`
                    *dst = *src;
                    dst = dst.add(1);
                    src = src.add(1);
                }
            }
        } else {
            while dst != end {
                *dst = *src;
                dst = dst.add(1);
                src = src.add(1);
            }
        }
    }

    dc.set_out_ptr(out_ptr);
    (*dc.get()).stream.bits = bits;
    (*dc.get()).stream.left = left;
    (*dc.get()).stream.chunk_ptr = data;
    1
}

