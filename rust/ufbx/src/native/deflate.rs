// -7: Bad block type
// -8: Truncated checksum (deprecated, reported as -9)
// -9: Checksum mismatch
// -10: Literal destination overflow
// -11: Bad distance code or distance of (30..31)
// -12: Match out of bounds
// -13: Bad lit/length code
// -14: Codelen Huffman Overfull
// -15: Codelen Huffman Underfull
// -16: Litlen Huffman Overfull
// -17: Litlen Huffman Underfull
// -18: Repeat 16 overflow
// -19: Repeat 17 overflow
// -20: Repeat 18 overflow
// -21: Bad codelen code
// -22: Distance Huffman: Overfull
// -23: Distance Huffman: Underfull
// -28: Cancelled
// -29: Invalid ufbx_inflate_input.internal_fast_bits value
// -30: Bad window size (ZLIB header)
// ufbx.c:3131-3276 `ufbx_inflate` (public entry; C ABI shim lives in capi.rs)
pub(crate) unsafe fn inflate(
    dst: *mut c_void,
    dst_size: usize,
    input: *const InflateInput,
    retain: *mut InflateRetain,
) -> isize {
    let ret_imp = retain as *mut InflateRetainImp;

    // `input` is unconditionally dereferenced throughout this function (no
    // NULL check on the public entry point), so a local shared borrow is
    // sound (rule 4) in place of repeated `(*input).field` derefs. `ret_imp`
    // is left as a raw pointer: it aliases the `trees` pointer threaded
    // through the block loop below across iterations, so an exclusive
    // borrow here would not obviously stay sound for the whole function.
    let input = &*input;

    let mut err: isize;
    // C: `ufbxi_deflate_context dc;` (uninitialized). Zero-init: C never reads
    // uninit fields except `stream.cancel_bits`, which upstream never writes —
    // it is read on cancellation (ufbx.c:2184) as stack garbage. Zero-init pins
    // that read to 0 (benign: cancellation is re-checked after every block).
    // ACCEPTED DIVERGENCE (fuzz-table ledger): because the block loop checks
    // `err < 0` before `(*dc.get()).stream.cancelled` (ufbx.c:3242-3245), C's garbage
    // bits can produce a data-dependent decode error (-10/-11/-12/-13) before
    // the -28 cancel return; pinned-0 bits make the mid-block cancellation
    // return code deterministic here, which may differ from a given C build.
    // No deterministic port can reproduce C's uninit read.
    let dc: DeflateContext = core::mem::zeroed();
    bit_stream_init(dc.stream_mut_ptr(), input);
    dc.set_out_begin(dst as *mut u8);
    dc.set_out_ptr(dst as *mut u8);
    dc.set_out_end((dst as *mut u8).add(dst_size));
    if input.internal_fast_bits != 0 {
        dc.set_fast_bits(input.internal_fast_bits as u32);
        if dc.fast_bits() < 1 || dc.fast_bits() == 9 || dc.fast_bits() > 10 {
            return -29;
        }
    } else {
        // TODO: Profile this
        dc.set_fast_bits(if input.total_size > 2048 { 10 } else { 8 });
    }

    let mut bits = (*dc.get()).stream.bits;
    let mut left = (*dc.get()).stream.left;
    let mut data = (*dc.get()).stream.chunk_ptr;

    bit_refill(&mut bits, &mut left, &mut data, dc.stream_mut_ptr());
    if (*dc.get()).stream.cancelled {
        return -28;
    }

    // Zlib header
    if !input.no_header {
        let cmf = (bits & 0xff) as usize;
        let flg = ((bits >> 8) as usize) & 0xff;
        bits >>= 16;
        left -= 16;

        if (cmf & 0xf) != 0x8 {
            return -1;
        }
        if (flg & 0x20) != 0 {
            return -2;
        }
        if (cmf << 8 | flg) % 31 != 0 {
            return -3;
        }
        if (cmf >> 4) > 7 {
            return -30;
        }
    }

    loop {
        bit_refill(&mut bits, &mut left, &mut data, dc.stream_mut_ptr());
        if (*dc.get()).stream.cancelled {
            return -28;
        }

        // Block header: [0:1] BFINAL [1:3] BTYPE
        let header = (bits as usize) & 0x7;
        bits >>= 3;
        left -= 3;

        let type_ = header >> 1;
        if type_ == 0 {
            // Round up to the next byte
            let align_bits = left & 0x7;
            bits >>= align_bits;
            left -= align_bits;

            let len = (bits & 0xffff) as usize;
            let nlen = ((bits >> 16) & 0xffff) as usize;
            if (len ^ nlen) != 0xffff {
                return -4;
            }
            if dc.out_end().offset_from(dc.out_ptr()) < len as isize {
                return -6;
            }
            bits >>= 32;
            left -= 32;

            (*dc.get()).stream.bits = bits;
            (*dc.get()).stream.left = left;
            (*dc.get()).stream.chunk_ptr = data;

            // Copy `len` bytes of literal data
            if bit_copy_bytes(dc.out_ptr() as *mut c_void, dc.stream_mut_ptr(), len) == 0 {
                return -5;
            }

            dc.set_out_ptr(dc.out_ptr().add(len));
        } else if type_ <= 2 {
            (*dc.get()).stream.bits = bits;
            (*dc.get()).stream.left = left;
            (*dc.get()).stream.chunk_ptr = data;

            // C: `ufbxi_trees tree_data;` — zero-init (see `dc` note above;
            // `ufbxi_init_dynamic_huff` writes everything that is later read).
            let mut tree_data: Trees = core::mem::zeroed(); // ufbxi_uninit
            let trees: *mut Trees; // ufbxi_uninit
            if type_ == 1 {
                // Static Huffman: Initialize the trees once and cache them in `retain`.
                if !(*ret_imp).initialized {
                    init_static_huff(&mut (*ret_imp).static_trees, input);
                    (*ret_imp).initialized = true;
                }
                trees = &mut (*ret_imp).static_trees;
            } else {
                // Dynamic Huffman
                err = init_dynamic_huff(&dc, &mut tree_data);
                if err != 0 {
                    return err;
                }
                trees = &mut tree_data;
            }

            loop {
                let fast_viable = (*trees).fast_bits == HUFF_FAST_BITS
                    && dc.out_end().offset_from(dc.out_ptr()) >= INFLATE_FAST_MIN_OUT as isize;

                // `ufbxi_inflate_block_fast()` needs a bit more upfront setup, see asserts on top of the function
                if fast_viable
                    && (*dc.get())
                        .stream
                        .chunk_yield
                        .offset_from((*dc.get()).stream.chunk_ptr)
                        >= INFLATE_FAST_MIN_IN as isize
                {
                    err = inflate_block_fast(&dc, trees) as isize;
                } else {
                    err = inflate_block_slow(&dc, trees, if fast_viable { 32 } else { usize::MAX })
                        as isize;
                }

                if err < 0 {
                    return err;
                }

                // `ufbxi_inflate_block()` returns normally on cancel so check it here
                if (*dc.get()).stream.cancelled {
                    return -28;
                }

                if err == 0 {
                    break;
                }
            }
        } else {
            // 0b11 - reserved (error)
            return -7;
        }

        bits = (*dc.get()).stream.bits;
        left = (*dc.get()).stream.left;
        data = (*dc.get()).stream.chunk_ptr;

        // BFINAL: End of stream
        if (header & 1) != 0 {
            break;
        }
    }

    // Check Adler-32
    {
        // Round up to the next byte
        let align_bits = left & 0x7;
        bits >>= align_bits;
        left -= align_bits;
        bit_refill(&mut bits, &mut left, &mut data, dc.stream_mut_ptr());
        if (*dc.get()).stream.cancelled {
            return -28;
        }

        if !input.no_checksum {
            let mut ref_ = bits as u32;
            ref_ = (ref_ >> 24) | ((ref_ >> 8) & 0xff00) | ((ref_ << 8) & 0xff0000) | (ref_ << 24);

            let checksum = adler32(
                dc.out_begin() as *const c_void,
                to_size(dc.out_ptr().offset_from(dc.out_begin())),
            );
            if ref_ != checksum {
                return -9;
            }
        }
    }

    dc.out_ptr().offset_from(dc.out_begin())
}

